-- The five schemas that own the tables (nobody logs in as these).
CREATE USER azs_business IDENTIFIED BY "243648" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
CREATE USER azs_auth     IDENTIFIED BY "243648" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
CREATE USER azs_inquiry  IDENTIFIED BY "243648" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
CREATE USER azs_audit    IDENTIFIED BY "243648" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
CREATE USER azs_outbox   IDENTIFIED BY "243648" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;

-- The application user: connects here, Flyway creates objects in the five schemas through it.
CREATE USER ASANZEMAN IDENTIFIED BY "243648"
    DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW,
      CREATE PROCEDURE, CREATE TRIGGER, CREATE TYPE, CREATE SYNONYM TO ASANZEMAN;

GRANT CREATE ANY TABLE, ALTER ANY TABLE, DROP ANY TABLE, CREATE ANY INDEX, DROP ANY INDEX,
      CREATE ANY SEQUENCE, DROP ANY SEQUENCE, SELECT ANY TABLE, INSERT ANY TABLE, UPDATE ANY TABLE,
      DELETE ANY TABLE, LOCK ANY TABLE, COMMENT ANY TABLE TO ASANZEMAN;
